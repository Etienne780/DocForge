// same as the code fence regex in MarkdownParser.extractFencedCode
const CODE_FENCE_TAG_REGEX = /^[\w#+.-]+$/;

/**
 * @param {Object} project
 * @returns {string} markdown
 */
export function buildFormatGuide(project) {
  const sections = [
    _buildHeader(project),
    _buildPreferences(project),
    _buildLayout(),
    _buildConfig(),
    _buildEntryFiles(),
    _buildEntryTypes(),
    _buildMarkdown(),
    _buildReferenceLinks(project),
    _buildLanguages(project),
    _buildRecipes(),
  ];

  return sections.filter(Boolean).join('\n\n') + '\n';
}

/**
 * @param {Object} project
 * @returns {boolean}
 */
export function isFormatGuideEnabled(project) {
  return project?.settings?.formatGuide?.enabled === true;
}

/**
 * @param {string} text - content of an existing guide file
 * @returns {boolean} true when the file was written by DocForge
 */
export function isGeneratedFormatGuide(text) {
  return (text ?? '').startsWith(FORMAT_GUIDE_MARKER);
}

// ─── Sections ───────────────────────────────────────────────────────────────

function _buildHeader(project) {
  return `${FORMAT_GUIDE_MARKER}
# ${APP_NAME} project format

> Generated by ${APP_NAME} ${APP_VERSION} (project format version ${PROJECT_SCHEMA_VERSION}) for the project "${String(project?.name ?? '').replace(/\r?\n/g, ' ')}".
> Do not edit this file: ${APP_NAME} rewrites it on every save.

This folder is a ${APP_NAME} documentation project. ${APP_NAME} is an app for writing and organizing
Markdown documentation and exports a project as one self-contained HTML document.
This file describes how the project is stored, so tools and AI assistants can read and edit it
without ${APP_NAME}. Everything below is generated from the ${APP_NAME} version that saved the project.

Terms: a **project** has **tabs**, every tab has a tree of **entries** (called nodes in the files).
Every entry is one Markdown file.`;
}

function _buildPreferences(project) {
  const preferences = (project?.settings?.formatGuide?.preferences ?? '').trim();
  if (!preferences)
    return null;

  return `## Author preferences

The author of this project wants new and changed content to follow these rules.
They take precedence over general writing conventions.

${preferences}`;
}

function _buildLayout() {
  return `## Folder layout

\`\`\`text
<project folder>/
  ${FILE_EXTENSION_PROJECT_CONFIG}   project settings, links, tabs and the entry tree (no content)
  ${FORMAT_GUIDE_FILE}     this file (generated)
  ${PROJECT_TABS_DIR}/
    <tab>/               one folder per tab
      <entry>.md         one file per entry, all flat - the nesting lives in the config
  ${PROJECT_THEMES_DIR}/                *${FILE_EXTENSION_DOCTHEME} - project themes (JSON, edited in ${APP_NAME})
  ${PROJECT_LANGUAGES_DIR}/             *${FILE_EXTENSION_SYNTAXDEFINITION} - project syntax highlighting definitions (JSON, edited in ${APP_NAME})
\`\`\`

Tab folders and entry files are named after the tab/entry name:
the characters \`< > : " / \\ | ? *\`, control characters and trailing dots are removed.
Names that collide (case insensitive) within the same scope get \` (2)\`, \` (3)\`, … appended.
A name with nothing left becomes \`Unnamed\`. ${APP_NAME} renames the files when an entry is renamed.

Any other file in the folder (like this one) is ignored when the project is loaded.`;
}

function _buildConfig() {
  const themeIds = getPresetDocThemes().map(theme => `\`${theme.id}\``).join(', ') || '-';

  return `## ${FILE_EXTENSION_PROJECT_CONFIG}

\`\`\`json
{
  "id": "project_…",
  "name": "Project name",
  "settings": {
    "isThemePreset": true,
    "currentThemeId": "theme_…",
    "formatGuide": { "enabled": true, "preferences": "" }
  },
  "languagesStyles": [],
  "links": [],
  "tabs": [
    {
      "id": "tab_…",
      "name": "Documentation",
      "folderName": "Documentation",
      "nodes": [
        {
          "id": "node_…",
          "name": "Getting started",
          "fileName": "Getting started",
          "type": "${DEFAULT_NODE_TYPE}",
          "children": []
        }
      ]
    }
  ]
}
\`\`\`

| Field | Meaning |
|---|---|
| \`id\` | Unique id of the project. Never change it. |
| \`name\` | Project name, shown as the document title. |
| \`settings.isThemePreset\` | \`true\`: \`currentThemeId\` is a built-in theme. \`false\`: it is the \`id\` of a theme in \`${PROJECT_THEMES_DIR}/\`. |
| \`settings.currentThemeId\` | Active theme. Built-in themes: ${themeIds}. |
| \`settings.formatGuide\` | Settings of this file: \`enabled\` and the author \`preferences\`. |
| \`languagesStyles\` | Project highlight colors for languages. Edited in ${APP_NAME}, leave as is. |
| \`links\` | Reference links, see [Reference links](#reference-links). |
| \`tabs[]\` | Tabs in display order. \`folderName\` is the folder in \`${PROJECT_TABS_DIR}/\`. |
| \`tabs[].nodes[]\` | Entry tree in display order. \`children\` holds the child entries. |
| \`node.fileName\` | File name of the entry in its tab folder, without \`.md\`. |
| \`node.type\` | Entry type, see [Entry types](#entry-types). Missing = \`${DEFAULT_NODE_TYPE}\`. |
| \`node.mergeDescendants\` | Only for \`${NODE_TYPE.MERGED}\` entries. Missing = \`${DEFAULT_NODE_MERGE_MODE}\`. |

Ids are a prefix plus random lower case letters and digits (\`tab_…\`, \`node_…\`, \`link_…\`).
They must be unique in the project.`;
}

function _buildEntryFiles() {
  return `## Entry files

Every entry file starts with a frontmatter block that holds its id and name, followed by the content:

\`\`\`md
---
id: node_lf3k2def4
name: Getting started
---

# Getting started

Content in Markdown…
\`\`\`

- \`id\` must be the same as the \`id\` of the entry in the config. Without an id, ${APP_NAME} assigns a new one.
- \`name\` is the display name and wins over the name in the config. Keep it on one line.
- Everything after the frontmatter is the entry content.
- Entries in the config without a file are kept as empty entries.
- Files that are not in the config are added at the end of their tab (top level).
- Tab folders that are not in the config become new tabs named after the folder.`;
}

function _buildEntryTypes() {
  const typeRows = Object.values(NODE_TYPE).map(type => [
    `\`${type}\`${type === DEFAULT_NODE_TYPE ? ' (default)' : ''}`,
    NODE_TYPE_INFO[type]?.label ?? type,
    NODE_TYPE_INFO[type]?.description ?? '',
  ]);
  const mergeRows = Object.values(NODE_MERGE_MODE).map(mode => [
    `\`${mode}\`${mode === DEFAULT_NODE_MERGE_MODE ? ' (default)' : ''}`,
    NODE_MERGE_MODE_INFO[mode]?.label ?? mode,
    NODE_MERGE_MODE_INFO[mode]?.description ?? '',
  ]);

  return `## Entry types

The \`type\` of an entry only changes how it shows up in the exported document, never the tree.

${_table(['type', 'Name', 'Export'], typeRows)}

For \`${NODE_TYPE.MERGED}\` entries \`mergeDescendants\` decides what happens with the children of the children:

${_table(['mergeDescendants', 'Name', 'Effect'], mergeRows)}

- Inside a merged page the type of a section entry is ignored, except that the content of a
  \`${NODE_TYPE.FOLDER}\` entry stays hidden (only its name is shown as a heading).
- Section headings are shifted down by their depth (\`#\` becomes \`##\`, …), at most to h${MAX_SECTION_HEADING_LEVEL}.
- The content of \`${NODE_TYPE.FOLDER}\` entries is never exported, so do not put documentation there.`;
}

function _buildMarkdown() {
  return `## Markdown

${APP_NAME} uses its own Markdown parser. Only the following syntax is supported:

| Syntax | Notes |
|---|---|
| \`# Heading\` … \`#### Heading\` | h1 to h4 only. |
| \`**bold**\`, \`*italic*\`, \`_italic_\`, \`***both***\` | |
| \`\` \`inline code\` \`\` | |
| Fenced code blocks | Three or more backticks with an optional language tag, see [Languages](#syntax-highlighting-languages). |
| \`- item\` / \`* item\` | Nested with 2 to 4 spaces per level. |
| \`1. item\` | Ordered lists. |
| \`\\| a \\| b \\|\` tables | Header row, separator row (\`\\|---\\|---\\|\`), then body rows. Every row starts and ends with \`\\|\`. |
| \`> quote\` | One line per quote. |
| \`---\` | Horizontal rule, on its own line. |
| \`[text](https://…)\` | External link, opens in a new tab. |
| \`[[slug]]\`, \`{#anchor}\` | Reference links and anchors, see [Reference links](#reference-links). |

Not supported: raw HTML (it is shown as text), images, strikethrough, task lists,
underlined (setext) headings and footnotes.

Code blocks:

- \`\`\`\` \`\`\`lang \`\`\`\` highlights the code with the language \`lang\`.
- \`\`\`\` \`\`\`diff \`\`\`\` or \`\`\`\` \`\`\`diff:lang \`\`\`\` marks lines starting with \`+\` / \`-\` as added / removed (optionally highlighted as \`lang\`).
- Unknown or missing tags show the code without highlighting.`;
}

function _buildReferenceLinks(project) {
  const links = getProjectLinks(project);
  const rows = links.map(link => {
    const target = findNodeInProject(project, link.target?.nodeId)?.node?.name ?? '(missing entry)';
    const anchor = link.target?.anchor ? ` #${link.target.anchor}` : '';
    return [`\`${link.slug}\``, _inline(link.name), _inline(target + anchor)];
  });

  const linkTable = rows.length
    ? _table(['Slug', 'Default text', 'Target'], rows)
    : '_This project has no links yet._';

  return `## Reference links

Links between entries are defined once in \`links\` in the config and used in the content by their slug.
If a target moves, only the link has to be changed.

| Syntax | Meaning |
|---|---|
| \`[[slug]]\` | Link, the text is the link's \`name\`. |
| \`[[slug\\|Text]]\` | Link with custom text. |
| \`{#name}\` | Anchor in an entry that a link can point to (\`a-z\`, \`0-9\`, \`-\`). |

Link object in \`links\`:

\`\`\`json
{ "id": "link_…", "slug": "getting-started", "name": "Getting started",
  "target": { "nodeId": "node_…", "anchor": null }, "refs": [] }
\`\`\`

- \`slug\`: lower case letters, digits and single \`-\`, unique in the project.
- \`target.anchor\`: \`null\` for the whole entry, otherwise the name of a \`{#name}\` anchor in the target entry.
- \`refs\`: entries that use the link. ${APP_NAME} recomputes it, an empty array is fine.
- Unknown slugs and links with a missing target are shown as broken links. Code is never scanned for links.

Links of this project:

${linkTable}`;
}

function _buildLanguages(project) {
  const builtInRows = [...getPresetLanguages()]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(lang => [_inline(lang.name), _fenceTags(lang)]);

  const projectLanguages = getLanguages(project);
  const projectRows = projectLanguages.map(lang => {
    const overlaps = getBuiltInLanguageOverlaps(lang.name, lang.aliases ?? []);
    const note = overlaps.length
      ? `Overrides built-in ${overlaps.map(o => _inline(o.lang.name)).join(', ')}`
      : '';
    return [_inline(lang.name), _fenceTags(lang), note];
  });

  const projectTable = projectRows.length
    ? _table(['Language', 'Code fence tags', 'Note'], projectRows)
    : '_This project has no own languages._';

  return `## Syntax highlighting languages

The tag of a code block is matched case insensitive against the name and the aliases of a language.
Project languages are checked first, so they replace a built-in language with the same tag.
Only tags made of letters, digits and \`_ # + . -\` work, so names with spaces need an alias.

Project languages (\`${PROJECT_LANGUAGES_DIR}/\`):

${projectTable}

Built-in languages:

${_table(['Language', 'Code fence tags'], builtInRows)}`;
}

function _buildRecipes() {
  return `## How to make changes

${APP_NAME} reloads the project when files change while it is open. Unsaved changes in ${APP_NAME}
overwrite the files on the next save, so make external changes while the project is saved.

- **Edit content:** change the Markdown below the frontmatter. Keep the frontmatter as it is.
- **Add an entry at the end of a tab:** create \`${PROJECT_TABS_DIR}/<tab folder>/<Name>.md\` with a frontmatter
  that only has \`name\` (or none). ${APP_NAME} adds it and assigns an id.
- **Add an entry at a specific position or as a child:** create the file with a new unique id in the
  frontmatter and add a node with the same \`id\`, \`name\`, \`fileName\`, \`type\` and \`"children": []\`
  at that position in the config tree.
- **Add a tab:** create a folder in \`${PROJECT_TABS_DIR}/\`, or add a tab with a new id, \`name\`,
  \`folderName\` and \`nodes\` to \`tabs\` in the config.
- **Rename an entry:** rename the file and change \`name\` in its frontmatter and \`name\` and \`fileName\` in the config.
  If only the file is renamed, the old entry stays (empty) and the file shows up as a new entry.
- **Move or reorder entries:** move the node object in the config tree. The file stays where it is,
  because files are always flat in their tab folder.
- **Move an entry to another tab:** move the file to the other tab folder and the node object to that tab.
- **Delete an entry:** delete the file and remove the node from the config. Move or delete its children
  too, and remove or retarget links that point to it.
- **Link entries:** add a link to \`links\` and use \`[[slug]]\` in the content, see [Reference links](#reference-links).

Do not:

- change or reuse ids, or give two entries the same id,
- put other \`.md\` files into the tab folders (every \`.md\` file there is an entry),
- edit \`*${FILE_EXTENSION_DOCTHEME}\`, \`*${FILE_EXTENSION_SYNTAXDEFINITION}\` and \`languagesStyles\` by hand, they are written by the ${APP_NAME} editors,
- edit this file, it is overwritten on every save.`;
}

// ─── Helpers ────────────────────────────────────────────────────────────────

function _fenceTags(lang) {
  const tags = [lang.name, ...(lang.aliases ?? [])]
    .filter(tag => typeof tag === 'string' && CODE_FENCE_TAG_REGEX.test(tag));
  const unique = [...new Map(tags.map(tag => [tag.toLowerCase(), tag])).values()];
  return unique.length ? unique.map(tag => `\`${tag}\``).join(', ') : '-';
}

/** Single line text, safe for a table cell. */
function _inline(text) {
  return String(text ?? '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');
}

function _table(headers, rows) {
  const line = (cells) => `| ${cells.join(' | ')} |`;
  return [line(headers), line(headers.map(() => '---')), ...rows.map(line)].join('\n');
}
